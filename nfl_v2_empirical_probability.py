#!/usr/bin/env python3
"""NFL V2 model-native conditional P(reach OWN projected mean).

The V2 XGBoost reg:absoluteerror champion only predicts an expected yardage
number. It does not predict a CDF. The old frontend mistakenly ranked V2's
29.8-yard forecast by HIGH/MEDIUM historical workload stability. Removing that
unrelated grade made Top4 empty. This separately estimates V2's predictive
distribution using its ACTUAL PREVIOUS 2026 out-of-sample errors.

STRICT CONTRACT:
  V2's frozen model was trained through 2025. Use ONLY completed 2026 prior-
  week V2 predictions (generated by replay without the target game's result)
  and their real actual yards to learn an empirical residual distribution.
  Similar-sized predicted yards use one market-specific k-nearest residual
  pool. The modeled event is strictly P(YDS>=round_0_6(V2 projected mean)).
  No sportsbook, other-model bootstrap, in-sample 2025 error or magic percent.
  The source sample count is actual completed games, NOT 10,000 Monte Carlo.
  Prior individual V2 signed errors can shift the distribution a small
  prespecified amount if an independently scored 2026 prequential audit
  supports that correction. No future same-week game can influence the pool.

These are uncalibrated observational probabilities, not proven betting edges
or a verified active/lineup/injury condition. Never silently label them official.
"""
from __future__ import annotations

from collections import defaultdict
import math
from pathlib import Path
import numpy as np

import nfl_yardage_v2 as v2

SOURCE = "V2_CONTEXT_2026_PREGAME_OUT_OF_SAMPLE_EMPIRICAL_ERRORS_V1"
EVENT = "P_YARDS_AT_LEAST_ROUNDED_PUBLISHED_MEAN"
MIN_MARKET_ERRORS = 60
NEAREST_N = 160
MIN_PRIOR_PLAYER_ERRORS = 2
# Fixed conservative personal adjustment: shrink first three earlier errors
# toward zero to limit any highly noisy tail swings. No parameter optimizers.
PLAYER_SHRINK = 6.0
MAX_PLAYER_SHIFT_YDS = 12.0

def whole_mean(value):
    if not isinstance(value,(float,int)) or not math.isfinite(value) or value<0:
        raise ValueError("INVALID_V2_PROJECTION_FOR_EVENT")
    floor=math.floor(value)
    return floor+(1 if value-floor>=0.6-1e-10 else 0)

def personal_shift(prior_residuals):
    seq=[float(x) for x in prior_residuals[-3:] if math.isfinite(x)]
    if len(seq)<MIN_PRIOR_PLAYER_ERRORS:return 0.
    raw=np.mean(seq)*len(seq)/(len(seq)+PLAYER_SHRINK)
    return float(max(-MAX_PLAYER_SHIFT_YDS,min(MAX_PLAYER_SHIFT_YDS,raw)))

def probability_from_prior(prior,forecast,rounded_target,player_id=None,use_role=False):
    """Only residuals from completed earlier weeks. Identical-market records.

    No synthetic simulation. Nearest-forecast residuals are a conditional
    empirical CDF: P(Y >= target | expected center around this player).
    Laplace smoothing guards the short empirical tail without claiming
    Bayesian calibration. Center shifts are allowed only from prior player
    residual errors and a forward-evaluated preset rule.
    """
    if len(prior)<MIN_MARKET_ERRORS:return None
    ordered=sorted(prior,key=lambda z:(abs(z["prediction"]-forecast),
                    z["season"],z["week"],z["player_id"]))
    sample=ordered[:NEAREST_N]
    errors=[x["residual"] for x in sample]
    player_hist=sorted((x for x in prior if x["player_id"]==player_id),
                        key=lambda z:(z["season"],z["week"]))
    personal=[x["residual"] for x in player_hist]
    shift=personal_shift(personal) if use_role else 0.
    # Error is actual - predicted. The current V2 point forecast remains
    # unchanged. The probability is attached to its own rounded mean.
    threshold=rounded_target-forecast-shift
    wins=sum(x>=threshold for x in errors)
    prob=(wins+1.)/(len(errors)+2.)
    return {
      "source":SOURCE,
      "event":EVENT,
      "target":int(rounded_target),
      "probability":round(prob,4),
      "model_reference_mean":round(forecast,1),
      "residual_sample_n":len(errors),
      "residual_total_prior_n":len(prior),
      "personal_prior_error_n":len(personal),
      "personal_asof_bias_yards":round(shift,2),
      "market_calibration":"NOT_FORWARD_CERTIFIED",
      "estimated_independently_of_sportsbook":True,
      "official_active_status_verified":False,
    }

def asof_2026_residuals(con,market,target_season,target_week):
    """Replays only fully completed *prior* weeks, same source model.

    Strictly valid for the champion fitted through 2025 predicting 2026.
    Refuses to report the historical 2025 in-sample residuals as holdout.
    """
    import xgboost as xgb
    if target_season!=2026 or not 1<=target_week<=22:
        raise ValueError("V2_2026_HOLDOUT_ONLY")
    path=v2.MODEL_DIR/f"nfl_{market}_v2.json"
    if not path.exists():raise FileNotFoundError("FROZEN_V2_CHAMPION_MISSING_"+market)
    rows,_,_=v2.History(con,market).replay(until=(target_season,target_week))
    held=[r for r in rows if r[0]["season"]==target_season and r[0]["week"]<target_week]
    if not held:return []
    bst=xgb.Booster()
    bst.load_model(str(path))
    pred=bst.predict(xgb.DMatrix(v2.to_matrix(held),feature_names=v2.FEATURES))
    return [
      {"season":int(r[0]["season"]),"week":int(r[0]["week"]),
       "player_id":str(r[0]["player_id"]),"name":v2.norm_name(r[0]["name"]),
       "team":r[0]["team"],"prediction":max(0.,float(y)),
       "v2_features":r[1],
       "actual":float(r[2]),"residual":float(r[2])-max(0.,float(y))}
      for r,y in zip(held,pred)
    ]

class ModelProbability:
    def __init__(self,con,season,week):
        self.rows={}
        self.meta={}
        self.role_adjustments={}
        self.learned_chosen={}
        self.learned_models={}
        self.learned_histories={}
        if season!=2026:return
        for market in v2.MARKETS:
            observed=asof_2026_residuals(con,market,season,week)
            self.rows[market]=observed
            report=prequential_audit(observed)
            # Independently evaluate a second probability model that uses
            # opportunity features and prior V2 misses. No promotion unless
            # its strictly chronological prequential Brier beats BOTH
            # empirical residuals and the constant-50% reference.
            import nfl_v2_learned_probability as learned
            learned_audit=learned.evaluate_model(observed)
            self.role_adjustments[market]=False
            self.meta[market]={**report,"learned_probability_head":learned_audit}
            approved=bool(learned_audit["promotion_eligible"])
            self.learned_chosen[market]=approved
            if approved:
                allrows,history=learned.with_asof_features(observed)
                self.learned_models[market]=learned.fit(allrows)
                self.learned_histories[market]=history

    def estimate(self,market,player_name,team,forecast,
                 current_features=None,player_id=None):
        observed=self.rows.get(market,[])
        pid=player_id
        if pid is None:
            candidate=[x for x in observed if x["name"]==v2.norm_name(player_name) and x["team"]==team]
            if candidate:pid=candidate[-1]["player_id"]
        if self.learned_chosen.get(market,False) and current_features is not None and pid:
            import nfl_v2_learned_probability as learned
            outcome=learned.predict_one(
                self.learned_models.get(market),
                self.learned_histories.get(market,{}),
                {"player_id":pid,"prediction":float(forecast)},
                current_features,len(observed))
            if outcome is not None:return outcome
        return probability_from_prior(
            observed,float(forecast),whole_mean(float(forecast)),
            pid,use_role=self.role_adjustments.get(market,False))

def prequential_audit(observed):
    """Forward validation 2026 Week6+ only (never forecasts one row using
    any result from that same week). Prevents grading on fitted data.
    Reports accuracy against a fixed 50% comparator and no model promotion.
    """
    by_week=defaultdict(list)
    for x in observed:by_week[x["week"]].append(x)
    brier,samples,role_brier=[],[],[]
    for week in sorted(by_week):
        prior=[x for x in observed if x["week"]<week]
        if len(prior)<MIN_MARKET_ERRORS:continue
        for x in by_week[week]:
            target=whole_mean(x["prediction"])
            p=probability_from_prior(prior,x["prediction"],target,x["player_id"])
            rp=probability_from_prior(prior,x["prediction"],target,x["player_id"],use_role=True)
            if p is None or rp is None:continue
            label=float(x["actual"]>=target)
            brier.append((p["probability"]-label)**2)
            role_brier.append((rp["probability"]-label)**2)
            samples.append((x,label,p["probability"]))
    return {
        "status":"FORWARD_DIAGNOSTIC_NOT_CALIBRATION_CERTIFIED",
        "forward_2026_prequential_n":len(brier),
        "forward_2026_prequential_brier":round(float(np.mean(brier)),4) if brier else None,
        "forward_2026_role_shadow_brier":round(float(np.mean(role_brier)),4) if role_brier else None,
        "constant_50pct_brier":.25,
        "source_sample_before_target_only":True,
        "role_adjustment_published":False,
        "independently_verified_active_status":False
    }
